/**
 * Insurance Service
 * Handles insurance document storage, chunk embedding, and vector search
 * Spine is the AI gatekeeper — all embedding generation happens here
 */

import { SupabaseClient } from "@supabase/supabase-js";

// ============================================================================
// Types
// ============================================================================

export interface InsuranceDocumentRecord {
  company_id: string;
  company_name: string;
  policy_name: string;
  doc_type: string;
  source_url: string;
  raw_text: string;
  cleaned_text: string;
  document_hash: string;
}

export interface InsuranceChunkInput {
  chunk_index: number;
  chunk_type: "body" | "table";
  text: string;
  char_start: number;
  char_end: number;
  metadata: Record<string, unknown>;
}

export interface InsuranceSearchResult {
  id: string;
  document_id: string;
  company_id: string;
  chunk_index: number;
  chunk_type: string;
  text: string;
  metadata: Record<string, unknown>;
  similarity: number;
}

// ============================================================================
// Document Deduplication
// ============================================================================

/**
 * Check if a document with the given hash already exists
 */
export async function insuranceDocumentExists(
  supabase: SupabaseClient,
  documentHash: string
): Promise<boolean> {
  const { data, error } = await supabase
    .from("insurance_documents")
    .select("id")
    .eq("document_hash", documentHash)
    .limit(1);

  if (error) {
    console.warn(`[Insurance] Hash check error: ${error.message}`);
    return false;
  }

  return (data?.length || 0) > 0;
}

// ============================================================================
// Document Storage
// ============================================================================

/**
 * Store an insurance document record
 * Returns the inserted document ID
 */
export async function storeInsuranceDocument(
  supabase: SupabaseClient,
  doc: InsuranceDocumentRecord
): Promise<string> {
  const { data, error } = await supabase
    .from("insurance_documents")
    .insert({
      company_id: doc.company_id,
      company_name: doc.company_name,
      policy_name: doc.policy_name,
      doc_type: doc.doc_type,
      source_url: doc.source_url,
      raw_text: doc.raw_text,
      cleaned_text: doc.cleaned_text,
      document_hash: doc.document_hash,
    })
    .select("id")
    .single();

  if (error) {
    throw new Error(`Failed to store insurance document: ${error.message}`);
  }

  return data.id;
}

// ============================================================================
// Chunk Storage
// ============================================================================

/**
 * Store insurance chunks with embeddings
 * Embeddings are pre-generated by the caller
 */
export async function storeInsuranceChunks(
  supabase: SupabaseClient,
  documentId: string,
  companyId: string,
  chunks: InsuranceChunkInput[],
  embeddings: number[][]
): Promise<number> {
  const rows = chunks.map((chunk, i) => ({
    document_id: documentId,
    company_id: companyId,
    chunk_index: chunk.chunk_index,
    chunk_type: chunk.chunk_type,
    text: chunk.text,
    embedding: JSON.stringify(embeddings[i]),
    char_start: chunk.char_start,
    char_end: chunk.char_end,
    metadata: chunk.metadata,
  }));

  // Insert in batches of 50 to avoid payload limits
  const BATCH_SIZE = 50;
  let totalInserted = 0;

  for (let i = 0; i < rows.length; i += BATCH_SIZE) {
    const batch = rows.slice(i, i + BATCH_SIZE);

    const { data, error } = await supabase
      .from("insurance_chunks")
      .insert(batch)
      .select("id");

    if (error) {
      throw new Error(
        `Failed to store insurance chunks (batch ${i}): ${error.message}`
      );
    }

    totalInserted += data?.length || 0;
  }

  return totalInserted;
}

// ============================================================================
// Vector Search
// ============================================================================

/**
 * Search insurance chunks using vector similarity
 * Calls the search_insurance_chunks RPC function
 */
export async function searchInsuranceChunks(
  supabase: SupabaseClient,
  queryEmbedding: number[],
  options: {
    limit?: number;
    company_id?: string;
    chunk_type?: string;
    min_similarity?: number;
  } = {}
): Promise<InsuranceSearchResult[]> {
  const {
    limit = 5,
    company_id,
    chunk_type,
    min_similarity = 0.5,
  } = options;

  const { data, error } = await supabase.rpc("search_insurance_chunks", {
    query_embedding: JSON.stringify(queryEmbedding),
    match_limit: limit,
    filter_company_id: company_id || null,
    filter_chunk_type: chunk_type || null,
  });

  if (error) {
    throw new Error(`Insurance search failed: ${error.message}`);
  }

  // Filter by minimum similarity
  return (data || []).filter(
    (result: InsuranceSearchResult) =>
      (result.similarity || 0) >= min_similarity
  );
}

// ============================================================================
// Context Formatting
// ============================================================================

/**
 * Format insurance search results into context string for LLM
 */
export function formatInsuranceContext(
  results: InsuranceSearchResult[]
): string {
  if (!results.length) {
    return "No relevant insurance context found.";
  }

  return results
    .map((result, i) => {
      const company = result.company_id || "Unknown";
      const chunkType = result.chunk_type || "body";
      const similarity = result.similarity?.toFixed(2) || "N/A";

      return `[Insurance Document ${i + 1}] (Company: ${company}, Type: ${chunkType}, Relevance: ${similarity})
${result.text}`;
    })
    .join("\n\n---\n\n");
}
